-- Additive personalized matching. Existing scores, histories and delivery rows stay untouched.
ALTER TABLE jobs ADD COLUMN legacy_admission_pending BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX jobs_legacy_pending_idx ON jobs(legacy_admission_pending,id);
CREATE TABLE vacancy_fact_revisions (
    job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
    job_revision BIGINT NOT NULL CHECK(job_revision>0),
    extractor_version VARCHAR(80) NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    source_input TEXT,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(job_id,job_revision,extractor_version)
);
CREATE TABLE vacancy_fact_state (
    job_id BIGINT PRIMARY KEY REFERENCES jobs(id) ON DELETE RESTRICT,
    job_revision BIGINT NOT NULL,
    extractor_version VARCHAR(80) NOT NULL,
    FOREIGN KEY(job_id,job_revision,extractor_version) REFERENCES vacancy_fact_revisions(job_id,job_revision,extractor_version) ON DELETE RESTRICT
);
CREATE TABLE matching_catalogue_state (
    id SMALLINT PRIMARY KEY CHECK(id=1),
    change_revision BIGINT NOT NULL CHECK(change_revision>=0)
);
INSERT INTO matching_catalogue_state VALUES(1,0);
CREATE TABLE matching_catalogue_changes (
    change_revision BIGINT PRIMARY KEY CHECK(change_revision>0),
    job_id BIGINT NOT NULL,
    job_revision BIGINT NOT NULL,
    extractor_version VARCHAR(80) NOT NULL,
    FOREIGN KEY(job_id,job_revision,extractor_version) REFERENCES vacancy_fact_revisions(job_id,job_revision,extractor_version) ON DELETE RESTRICT
);
CREATE TABLE candidate_match_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL,
    search_profile_version BIGINT NOT NULL,
    job_revision BIGINT NOT NULL,
    extractor_version VARCHAR(80) NOT NULL,
    scorer_version VARCHAR(80) NOT NULL,
    eligibility VARCHAR(20) NOT NULL CHECK(eligibility IN ('ELIGIBLE','INELIGIBLE','UNKNOWN')),
    compatibility_score INTEGER NOT NULL CHECK(compatibility_score BETWEEN 0 AND 100),
    recommendation_score INTEGER CHECK(recommendation_score BETWEEN 0 AND 100),
    evidence_coverage INTEGER NOT NULL CHECK(evidence_coverage BETWEEN 0 AND 100),
    payload TEXT NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    computed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK((eligibility='INELIGIBLE' AND recommendation_score IS NULL) OR (eligibility<>'INELIGIBLE' AND recommendation_score IS NOT NULL AND recommendation_score=compatibility_score)),
    UNIQUE(candidate_id,job_id,search_profile_version,job_revision,extractor_version,scorer_version),
    UNIQUE(candidate_id,job_id,id),
    FOREIGN KEY(candidate_id,search_profile_version) REFERENCES search_profile_revisions(candidate_id,revision) ON DELETE RESTRICT,
    FOREIGN KEY(job_id,job_revision,extractor_version) REFERENCES vacancy_fact_revisions(job_id,job_revision,extractor_version) ON DELETE RESTRICT
);
CREATE INDEX candidate_match_listing_idx ON candidate_match_results(candidate_id,search_profile_version,extractor_version,scorer_version,eligibility,compatibility_score DESC,published_at DESC,job_id DESC);
CREATE TABLE candidate_match_current (
    candidate_id BIGINT NOT NULL REFERENCES candidates(id) ON DELETE RESTRICT,
    job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
    result_id BIGINT NOT NULL,
    PRIMARY KEY(candidate_id,job_id),
    FOREIGN KEY(candidate_id,job_id,result_id) REFERENCES candidate_match_results(candidate_id,job_id,id) ON DELETE RESTRICT
);
CREATE TABLE candidate_matching_state (
    candidate_id BIGINT PRIMARY KEY REFERENCES candidates(id) ON DELETE RESTRICT,
    profile_revision BIGINT NOT NULL,
    extractor_version VARCHAR(80) NOT NULL,
    scorer_version VARCHAR(80) NOT NULL,
    phase VARCHAR(20) NOT NULL CHECK(phase IN ('NOT_READY','BACKFILL','READY','FAILED')),
    high_water_job_id BIGINT NOT NULL DEFAULT 0,
    next_job_id BIGINT NOT NULL DEFAULT 0,
    event_cursor BIGINT NOT NULL DEFAULT 0,
    publication_revision BIGINT NOT NULL DEFAULT 0,
    lease_token BIGINT NOT NULL DEFAULT 0,
    lease_until TIMESTAMP WITH TIME ZONE,
    last_claimed TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
    retry_after TIMESTAMP WITH TIME ZONE,
    failure_category VARCHAR(80),
    FOREIGN KEY(candidate_id,profile_revision) REFERENCES search_profile_revisions(candidate_id,revision) ON DELETE RESTRICT
);
CREATE INDEX matching_work_claim_idx ON candidate_matching_state(phase,retry_after,lease_until,last_claimed,candidate_id);
