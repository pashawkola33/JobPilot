-- Additive only: no consent, discovery or notification history is inferred for existing accounts/jobs.
ALTER TABLE auth_sessions ADD CONSTRAINT auth_session_notification_owner_uk UNIQUE(candidate_id,telegram_user_id,token_hash);
CREATE TABLE notification_preferences (
 candidate_id BIGINT PRIMARY KEY REFERENCES candidates(id) ON DELETE RESTRICT,
 revision BIGINT NOT NULL DEFAULT 0 CHECK(revision>=0),
 generation BIGINT NOT NULL DEFAULT 0 CHECK(generation>=0),
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 paused BOOLEAN NOT NULL DEFAULT FALSE,
 immediate BOOLEAN NOT NULL DEFAULT TRUE,
 digest BOOLEAN NOT NULL DEFAULT FALSE,
 minimum_score INTEGER NOT NULL DEFAULT 85 CHECK(minimum_score BETWEEN 0 AND 100),
 timezone VARCHAR(80) NOT NULL DEFAULT 'UTC',
 quiet_start VARCHAR(5), quiet_end VARCHAR(5),
 eligibility_policy VARCHAR(30) NOT NULL DEFAULT 'ELIGIBLE_ONLY' CHECK(eligibility_policy='ELIGIBLE_ONLY'),
 baseline_revision BIGINT NOT NULL DEFAULT 0 CHECK(baseline_revision>=0),
 event_cursor BIGINT NOT NULL DEFAULT 0 CHECK(event_cursor>=0),
 consent_session_hash VARCHAR(64), telegram_user_id BIGINT, credential_scope VARCHAR(64),
 consent_policy VARCHAR(40), consent_at TIMESTAMP WITH TIME ZONE,
 revoked_at TIMESTAMP WITH TIME ZONE,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK(NOT enabled OR (immediate OR digest)),
 CHECK((quiet_start IS NULL AND quiet_end IS NULL) OR (quiet_start IS NOT NULL AND quiet_end IS NOT NULL AND quiet_start<>quiet_end)),
 CHECK(NOT enabled OR (consent_session_hash IS NOT NULL AND telegram_user_id IS NOT NULL AND credential_scope IS NOT NULL AND consent_policy IS NOT NULL AND consent_at IS NOT NULL)),
 FOREIGN KEY(candidate_id,telegram_user_id,consent_session_hash) REFERENCES auth_sessions(candidate_id,telegram_user_id,token_hash) ON DELETE RESTRICT
);
CREATE TABLE notification_preference_revisions (
 candidate_id BIGINT NOT NULL REFERENCES notification_preferences(candidate_id) ON DELETE RESTRICT,
 revision BIGINT NOT NULL CHECK(revision>0), expected_revision BIGINT NOT NULL CHECK(expected_revision>=0),
 request_id VARCHAR(64) NOT NULL, payload TEXT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 PRIMARY KEY(candidate_id,revision), UNIQUE(candidate_id,request_id), CHECK(revision=expected_revision+1)
);
CREATE TABLE notification_connections (
 candidate_id BIGINT PRIMARY KEY REFERENCES candidates(id) ON DELETE RESTRICT,
 telegram_user_id BIGINT NOT NULL, chat_id BIGINT NOT NULL CHECK(chat_id>0),
 credential_scope VARCHAR(64) NOT NULL CHECK(CHAR_LENGTH(credential_scope)=64),
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONNECTED','BLOCKED','UNAVAILABLE','DISCONNECTED')),
 activated_at TIMESTAMP WITH TIME ZONE NOT NULL, disconnected_at TIMESTAMP WITH TIME ZONE,
 CHECK(chat_id=telegram_user_id),
 FOREIGN KEY(telegram_user_id,candidate_id) REFERENCES telegram_identities(telegram_user_id,candidate_id) ON DELETE RESTRICT
);
CREATE TABLE notification_activation_challenges (
 token_hash VARCHAR(64) PRIMARY KEY CHECK(CHAR_LENGTH(token_hash)=64),
 candidate_id BIGINT NOT NULL REFERENCES notification_preferences(candidate_id) ON DELETE RESTRICT,
 telegram_user_id BIGINT NOT NULL, session_hash VARCHAR(64) NOT NULL,
 credential_scope VARCHAR(64) NOT NULL CHECK(CHAR_LENGTH(credential_scope)=64),
 preference_revision BIGINT NOT NULL CHECK(preference_revision>0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 consumed_at TIMESTAMP WITH TIME ZONE, revoked_at TIMESTAMP WITH TIME ZONE,
 CHECK(expires_at>created_at),
 FOREIGN KEY(candidate_id,telegram_user_id,session_hash) REFERENCES auth_sessions(candidate_id,telegram_user_id,token_hash) ON DELETE RESTRICT
);
CREATE INDEX notification_challenge_candidate_idx ON notification_activation_challenges(candidate_id,created_at);
CREATE TABLE notification_discoveries (
 job_id BIGINT PRIMARY KEY REFERENCES jobs(id) ON DELETE RESTRICT,
 discovery_revision BIGINT NOT NULL UNIQUE CHECK(discovery_revision>0),
 discovered_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE notification_digest_envelopes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 candidate_id BIGINT NOT NULL REFERENCES candidates(id) ON DELETE RESTRICT,
 local_date DATE NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(candidate_id,local_date), UNIQUE(candidate_id,id)
);
CREATE TABLE notification_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 candidate_id BIGINT NOT NULL REFERENCES candidates(id) ON DELETE RESTRICT,
 mode VARCHAR(20) NOT NULL CHECK(mode IN ('IMMEDIATE','DIGEST')),
 envelope_id BIGINT,
 fence BIGINT NOT NULL CHECK(fence>0),
 local_date DATE NOT NULL, timezone VARCHAR(80) NOT NULL,
 payload TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(candidate_id,id),
 FOREIGN KEY(candidate_id,envelope_id) REFERENCES notification_digest_envelopes(candidate_id,id) ON DELETE RESTRICT
);
CREATE TABLE notification_attempt_outcomes (
 attempt_id BIGINT PRIMARY KEY REFERENCES notification_attempts(id) ON DELETE RESTRICT,
 state VARCHAR(20) NOT NULL CHECK(state IN ('SENDING','SENT','RETRY','CANCELED','FAILED','UNCERTAIN')),
 category VARCHAR(80), telegram_message_id BIGINT CHECK(telegram_message_id>0), completed_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE notification_outbox (
 candidate_id BIGINT NOT NULL REFERENCES notification_preferences(candidate_id) ON DELETE RESTRICT,
 job_id BIGINT NOT NULL REFERENCES notification_discoveries(job_id) ON DELETE RESTRICT,
 result_id BIGINT NOT NULL,
 generation BIGINT NOT NULL CHECK(generation>0),
 state VARCHAR(20) NOT NULL CHECK(state IN ('PENDING','RETRY','CLAIMED','SENDING','SENT','CANCELED','FAILED','UNCERTAIN','DROPPED')),
 mode VARCHAR(20) CHECK(mode IN ('IMMEDIATE','DIGEST')),
 fence BIGINT NOT NULL DEFAULT 0 CHECK(fence>=0), attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
 lease_until TIMESTAMP WITH TIME ZONE, next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 attempt_id BIGINT, reason VARCHAR(80), sent_at TIMESTAMP WITH TIME ZONE,
 PRIMARY KEY(candidate_id,job_id),
 FOREIGN KEY(candidate_id,job_id,result_id) REFERENCES candidate_match_results(candidate_id,job_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(candidate_id,attempt_id) REFERENCES notification_attempts(candidate_id,id) ON DELETE RESTRICT,
 CHECK(expires_at>created_at)
);
CREATE INDEX notification_outbox_claim_idx ON notification_outbox(state,next_attempt_at,candidate_id,job_id);
CREATE INDEX notification_attempt_budget_idx ON notification_attempts(candidate_id,created_at,local_date,mode);
CREATE TABLE notification_runtime_state (
 id SMALLINT PRIMARY KEY CHECK(id=1), runtime_epoch VARCHAR(64) NOT NULL CHECK(CHAR_LENGTH(runtime_epoch)=64)
);
